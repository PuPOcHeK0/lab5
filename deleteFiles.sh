#!/bin/bash

# Функция для вывода подсказки при некорректном вызове
usage() {
    echo "Ошибка: некорректный ввод параметров."
    echo "Порядок указания ключей и параметров:"
    echo "  $0 <имя_файла>          - удалить файл с точным именем"
    echo "  $0 -p <шаблон>          - удалить все файлы, содержащие подстроку <шаблон> в имени"
    exit 1
}

# Проверка количества аргументов
if [ $# -lt 1 ] || [ $# -gt 2 ]; then
    usage
fi

USE_PATTERN=0
TARGET=""

# Разбор аргументов
if [ "$1" = "-p" ]; then
    if [ $# -ne 2 ]; then
        usage
    fi
    USE_PATTERN=1
    TARGET="$2"
else
    TARGET="$1"
fi

# Проверка, что целевое имя/шаблон не пустое
if [ -z "$TARGET" ]; then
    usage
fi

if [ "$USE_PATTERN" -eq 0 ]; then
    # === УДАЛЕНИЕ ПО ТОЧНОМУ ИМЕНИ ===
    # Явно используем относительный путь "./" для безопасности
    if [ -f "./$TARGET" ]; then
        rm "./$TARGET"
        echo " Файл './$TARGET' успешно удалён."
    else
        echo " Ошибка: файл './$TARGET' не найден в текущей директории."
        exit 1
    fi
else
    # === УДАЛЕНИЕ ПО ШАБЛОНУ (ПОДСТРОКЕ) ===
    echo " Поиск файлов в текущей директории, содержащих '$TARGET' в имени..."
    
    # find . -maxdepth 1 ищет только в текущей папке (относительный путь ./)
    # -type f ищет только файлы
    # -name "*$TARGET*" ищет по подстроке (case-sensitive по умолчанию)
    while IFS= read -r -d '' file; do
        rm "$file"
        echo " Удалено: $file"
    done < <(find . -maxdepth 1 -type f -name "*$TARGET*" -print0)

    # Проверка, было ли что-то удалено
    if [ $? -ne 0 ] && [ ! -f "./$TARGET" ]; then
        echo " Файлы, соответствующие шаблону '$TARGET', не найдены."
    else
        echo " Готово. Все найденные файлы удалены."
    fi
fi
